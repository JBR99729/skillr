import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(
  ROOT,
  "curriculum-question-banks/banks/foundation/foundation-maths-production-v2.json"
);
const visualPath = path.join(
  ROOT,
  "quiz/assets/daily-drills/foundation-maths-visuals-v2.svg"
);
const outputPath = path.join(
  ROOT,
  "quiz/assets/daily-drills/foundation-maths-production-v2.js"
);

const source = JSON.parse(fs.readFileSync(sourcePath, "utf8"));
const svg = fs.readFileSync(visualPath, "utf8");
const symbolIds = new Set(
  [...svg.matchAll(/<symbol\s+id="([^"]+)"/g)].map((match) => match[1])
);

function escapeAttribute(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

function convert(item) {
  const answers = Array.isArray(item.answers)
    ? item.answers.map((answer) => String(answer.label ?? answer.text ?? answer))
    : [];
  const visual = item.visual;
  let visualHtml;

  if (visual) {
    if (!symbolIds.has(visual.symbol_id)) {
      throw new Error(`Missing SVG symbol ${visual.symbol_id} for ${item.id}`);
    }
    const asset = escapeAttribute(visual.asset_path);
    const symbol = escapeAttribute(visual.symbol_id);
    const viewBox = escapeAttribute(visual.view_box || "0 0 720 180");
    const alt = escapeAttribute(visual.alt_text || visual.fallback_text || "Maths diagram");
    visualHtml = `<svg role="img" aria-label="${alt}" viewBox="${viewBox}" style="display:block;width:min(100%,720px);height:auto;margin:0 auto"><use href="${asset}#${symbol}"></use></svg>`;
  }

  const converted = {
    id: item.id,
    year: "F",
    subject: "math",
    skill: item.topic,
    set: item.set,
    difficulty: item.difficulty,
    type: item.type,
    question: item.question,
    answers,
    explanation: item.explanation?.summary || String(item.explanation || ""),
    hint: item.explanation?.hint || "",
    audioPrompt: item.audio_prompt || item.question,
    learningArea: item.curriculumCode,
    curriculumCode: item.curriculumCode,
    bank: item.bank,
    source: item.source,
    printable: item.printable !== false
  };

  if (visual) {
    converted.visual = visual.fallback_text || visual.alt_text || "";
    converted.visualHtml = visualHtml;
    converted.visualAlt = visual.alt_text || "";
  }

  if (["single", "true-false"].includes(item.type)) {
    converted.correct = item.correct_index;
  } else if (item.type === "multiple") {
    converted.correct = item.correct_indexes;
    converted.instruction = item.instruction;
  } else if (item.type === "number") {
    converted.correct = item.correct_answer;
    converted.tolerance = item.tolerance || 0;
    converted.placeholder = item.placeholder;
  } else if (["text", "fill-blank"].includes(item.type)) {
    converted.correct = item.correct_answer;
    converted.acceptedAnswers = item.accepted_answers || [item.correct_answer];
    if (item.type === "fill-blank") converted.template = item.template;
  } else if (item.type === "order") {
    converted.items = item.items;
    converted.correct = item.correct_answer;
    converted.instruction = item.instruction;
  }

  return converted;
}

const topics = Object.fromEntries(
  source.topics.map((topic) => [topic.slug, topic.items.map(convert)])
);

const banner = `/* Generated by scripts/build_foundation_maths_daily_drills_v2.mjs. Do not edit directly. */\n`;
const runtime = `"use strict";\n(() => {\n  window.SkillrDailyProductionBanks = window.SkillrDailyProductionBanks || {};\n  window.SkillrDailyProductionBanks.F = window.SkillrDailyProductionBanks.F || {};\n  window.SkillrDailyProductionBanks.F.math = ${JSON.stringify(topics)};\n})();\n`;

fs.writeFileSync(outputPath, banner + runtime);
console.log(
  JSON.stringify({
    topics: Object.keys(topics).length,
    items: Object.values(topics).reduce((sum, items) => sum + items.length, 0),
    visuals: symbolIds.size,
    output: path.relative(ROOT, outputPath)
  })
);
